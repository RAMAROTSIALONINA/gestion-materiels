-- =====================================================================
--  0002 — Signalements des employés (décision du 11/11/2026)
--  Un employé signale une panne, une perte ou un retour souhaité sur un
--  matériel qui lui est affecté ; le gestionnaire le prend en charge puis le
--  clôt avec une réponse. La fonction s'active dans les paramètres
--  (cahier des charges § 1.3 : « si cette fonction est activée »).
--  Appliquée par « npm run db:migrer », dans une transaction.
-- =====================================================================

-- Paramètres : contrôle des nouvelles clés.
CREATE OR REPLACE FUNCTION trg_parametres_controle() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.cle = 'fuseau_horaire' THEN
    PERFORM now() AT TIME ZONE NEW.valeur;          -- erreur si le fuseau n'existe pas
  ELSIF NEW.cle IN ('prefixe_materiel', 'prefixe_article', 'prefixe_mouvement')
        AND NEW.valeur !~ '^[A-Z]{2,6}$' THEN
    RAISE EXCEPTION 'Préfixe invalide pour % : 2 à 6 lettres majuscules', NEW.cle
      USING ERRCODE = 'GM006';
  ELSIF NEW.cle IN ('connexion_tentatives_max', 'connexion_verrouillage_minutes')
        AND NEW.valeur !~ '^[1-9][0-9]{0,3}$' THEN
    RAISE EXCEPTION 'Nombre entier attendu pour %', NEW.cle USING ERRCODE = 'GM006';
  ELSIF NEW.cle = 'signalements_actifs' AND NEW.valeur NOT IN ('oui', 'non') THEN
    RAISE EXCEPTION 'Valeur « oui » ou « non » attendue pour %', NEW.cle USING ERRCODE = 'GM006';
  ELSIF NEW.cle = 'nom_societe' AND (btrim(NEW.valeur) = '' OR length(NEW.valeur) > 100) THEN
    RAISE EXCEPTION 'Nom de la société : 1 à 100 caractères' USING ERRCODE = 'GM006';
  END IF;
  NEW.modifie_le := now();
  RETURN NEW;
END $$;

INSERT INTO parametres (cle, valeur, description) VALUES
  ('signalements_actifs', 'non', 'Les employés peuvent signaler une panne, une perte ou un retour souhaité (oui / non)');

CREATE TABLE signalements (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  materiel_id    bigint NOT NULL REFERENCES materiels (id),
  affectation_id bigint REFERENCES affectations (id),
  auteur_id      bigint NOT NULL REFERENCES utilisateurs (id),
  type           text NOT NULL CONSTRAINT signalements_type CHECK (type IN ('PANNE', 'PERTE', 'RETOUR_SOUHAITE', 'AUTRE')),
  description    text NOT NULL CONSTRAINT signalements_description CHECK (length(btrim(description)) BETWEEN 5 AND 2000),
  statut         text NOT NULL DEFAULT 'OUVERT'
                   CONSTRAINT signalements_statut CHECK (statut IN ('OUVERT', 'PRIS_EN_CHARGE', 'CLOS')),
  cree_le        timestamptz NOT NULL DEFAULT now(),
  traite_par     bigint REFERENCES utilisateurs (id),
  traite_le      timestamptz,
  reponse        text,
  CONSTRAINT signalements_traitement CHECK ((statut = 'OUVERT') = (traite_par IS NULL AND traite_le IS NULL)),
  CONSTRAINT signalements_cloture_motivee CHECK (statut <> 'CLOS' OR length(btrim(coalesce(reponse, ''))) >= 3)
);
CREATE INDEX signalements_statut_idx ON signalements (statut, cree_le DESC);
CREATE INDEX signalements_materiel_idx ON signalements (materiel_id);
CREATE INDEX signalements_auteur_idx ON signalements (auteur_id, cree_le DESC);

-- Un signalement ne se supprime pas ; seul son traitement évolue, dans l'ordre
-- OUVERT → PRIS_EN_CHARGE → CLOS (ou OUVERT → CLOS) ; clos, il est figé.
CREATE FUNCTION trg_signalements_avant() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Un signalement ne se supprime pas : il se clôt avec une réponse' USING ERRCODE = 'GM003';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.statut <> 'OUVERT' THEN
      RAISE EXCEPTION 'Un signalement se crée ouvert' USING ERRCODE = 'GM002';
    END IF;
    NEW.auteur_id := coalesce(NEW.auteur_id, utilisateur_courant());
    NEW.cree_le   := now();
    RETURN NEW;
  END IF;

  IF OLD.statut = 'CLOS' THEN
    RAISE EXCEPTION 'Ce signalement est clos : il ne se modifie plus' USING ERRCODE = 'GM002';
  END IF;
  IF (NEW.materiel_id, NEW.affectation_id, NEW.auteur_id, NEW.type, NEW.description, NEW.cree_le)
     IS DISTINCT FROM
     (OLD.materiel_id, OLD.affectation_id, OLD.auteur_id, OLD.type, OLD.description, OLD.cree_le) THEN
    RAISE EXCEPTION 'Le contenu d’un signalement ne se modifie pas' USING ERRCODE = 'GM002';
  END IF;
  IF NEW.statut = 'OUVERT' AND OLD.statut <> 'OUVERT' THEN
    RAISE EXCEPTION 'Un signalement pris en charge ne redevient pas ouvert' USING ERRCODE = 'GM002';
  END IF;
  IF NEW.statut IS DISTINCT FROM OLD.statut OR NEW.reponse IS DISTINCT FROM OLD.reponse THEN
    NEW.traite_par := utilisateur_courant();
    NEW.traite_le  := now();
  END IF;
  RETURN NEW;
END $$;

CREATE TRIGGER signalements_avant BEFORE INSERT OR UPDATE OR DELETE ON signalements
  FOR EACH ROW EXECUTE FUNCTION trg_signalements_avant();
CREATE TRIGGER signalements_pas_de_vidage BEFORE TRUNCATE ON signalements
  FOR EACH STATEMENT EXECUTE FUNCTION trg_interdire_vidage();
